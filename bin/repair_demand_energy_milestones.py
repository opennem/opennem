#!/usr/bin/env uv run
"""Rebuild the demand energy milestone series after the #605 unit fix.

`market_summary.demand_energy` was stored 1000x low (GWh in a column labelled MWh), so every
`*.demand.energy.*` milestone recorded a GWh magnitude against an MWh unit. The 2009/2010 era rows
are worse again: they were generated by the backlog path, which stamped them `MW`, so the series
carries three incompatible semantics and the high records have been frozen since 2010 because the
GWh-scale values could not numerically beat the legacy MW ones.

It purges the whole `*.demand.energy.*` series and re-derives it from ClickHouse, which holds data
from 1999. The `*.demand.power.interval.*` series is left alone: it reads `market_summary.demand`
(MW), which the #605 fix does not touch.

REQUIRED RUN ORDER
------------------
1. deploy the #605 code and let the ARQ workers cycle, so no process is still writing old-scale
   values into `market_summary`
2. run the ClickHouse `market_summary` backfill to completion
3. rebuild `market_summary_daily_mv` and `market_summary_monthly_mv`
4. run this script promptly after step 3

Purge and rebuild are NOT atomic — the delete is one PG statement, the rebuild is a long ClickHouse
analysis — and the incremental milestone worker can write into the gap. The purge takes a
transaction-scoped advisory lock so two runs cannot delete concurrently, but nothing here holds a
lock across the whole run: PG sits behind pgbouncer in transaction-pooling mode, where a
session-level lock is released at commit and is re-entrant between runs sharing a backend, so a
whole-run lock cannot be expressed. Run order and the post-rebuild check below are the real
protection, and neither stops the incremental path. What that path does on
collision is settled by `check_and_persist_milestones_chunked`, which bulk-inserts with
`on_conflict_do_nothing` against the `(record_id, interval)` primary key: a row the incremental
worker already wrote is SKIPPED by the rebuild, never duplicated and never overwritten. So a race
cannot corrupt or double up the series.

The damaging case is narrower: mid-purge the series is empty, so `get_current_milestone_state()`
returns nothing for these record_ids and the incremental worker treats the next interval it sees as
a brand new record, minting a row the full-history rebuild would never have produced. That is what
the post-rebuild validation catches — it compares the rows PG ends up holding against the distinct
records the rebuild attempted, and exits non-zero on a surplus. A racer landing on a key the rebuild
also wanted is benign and deliberately not flagged: both come from the same ClickHouse data under
the same code, differing only in the linkage fields. Re-run from a quiet moment to resolve a surplus.

Usage:
    uv run bin/repair_demand_energy_milestones.py --dry-run
    uv run bin/repair_demand_energy_milestones.py
    ENV=production uv run bin/repair_demand_energy_milestones.py --dry-run
    ENV=production uv run bin/repair_demand_energy_milestones.py
"""

import argparse
import asyncio
import logging

from sqlalchemy import text

from opennem.db import get_read_session, get_write_session
from opennem.recordreactor.backlog import run_milestone_analysis
from opennem.recordreactor.schema import MilestonePeriod, MilestoneType
from opennem.schema.network import NetworkNEM
from opennem.utils.dates import get_last_completed_interval_for_network

logger = logging.getLogger("opennem.bin.repair_demand_energy_milestones")

# Matches every network, region, period and aggregate of the demand energy series, including the
# legacy MW-united rows. Excludes `*.demand.power.interval.*`, which the #605 fix does not affect.
DEMAND_ENERGY_RECORD_ID_PATTERN = "%.demand.energy.%"

# Day and up only — demand at the interval period is power (MW) and is not being rebuilt.
REBUILD_PERIODS = [
    MilestonePeriod.day,
    MilestonePeriod.month,
    MilestonePeriod.quarter,
    MilestonePeriod.year,
]

# Fixed key so two runs cannot purge concurrently. Transaction-scoped on purpose: PG is behind
# pgbouncer in transaction-pooling mode, where every session lands on the same shared server backend
# (verified on dev — four consecutive get_write_session() calls all reported one pg_backend_pid).
# A session-level pg_advisory_lock is therefore useless here twice over: commit hands the backend
# back so the lock is dropped, and while it is held a second run sharing that backend re-acquires it
# re-entrantly and sees success. pg_advisory_xact_lock is bound to the transaction, so it behaves
# correctly through the pooler. It cannot span the rebuild — see the module docstring.
ADVISORY_LOCK_KEY = 605605605


async def _summarise_existing() -> list[tuple[str, int, str | None]]:
    """Per record_id counts and the distinct units currently stored."""
    async with get_read_session() as session:
        result = await session.execute(
            text("""
                select record_id, count(*), string_agg(distinct value_unit, ',')
                from milestones
                where record_id like :pattern
                group by record_id
                order by record_id
            """),
            {"pattern": DEMAND_ENERGY_RECORD_ID_PATTERN},
        )
        return [(row[0], row[1], row[2]) for row in result]


async def _periods_matched_by_purge() -> list[str]:
    """Distinct period values the purge pattern would delete."""
    async with get_read_session() as session:
        result = await session.execute(
            text("""
                select distinct coalesce(period, '<null>')
                from milestones
                where record_id like :pattern
                order by 1
            """),
            {"pattern": DEMAND_ENERGY_RECORD_ID_PATTERN},
        )
        return [row[0] for row in result]


def _assert_purge_matches_rebuild(periods: list[str]) -> None:
    """The purge is pattern-based and the rebuild is period-scoped, so they can drift apart.

    Anything deleted that the rebuild does not regenerate is silent data loss, so fail loudly
    rather than discover it after the fact.
    """
    rebuildable = {period.value for period in REBUILD_PERIODS}
    orphaned = [period for period in periods if period not in rebuildable]

    if orphaned:
        raise SystemExit(
            f"Purge pattern {DEMAND_ENERGY_RECORD_ID_PATTERN!r} matches periods {orphaned} that the rebuild "
            f"does not cover ({sorted(rebuildable)}). Deleting them would be unrecoverable — add them to "
            f"REBUILD_PERIODS or narrow the pattern before running."
        )


def _assert_rebuild_sane(units: list[str], stored: int, attempted: int) -> None:
    """Post-conditions for a successful rebuild. Any failure exits non-zero rather than logging.

    A surplus over what the rebuild attempted means the incremental worker minted rows during the
    purge/rebuild window that the full-history rebuild would not have produced — those rows survive
    because persistence inserts with on_conflict_do_nothing.
    """
    if units != ["MWh"]:
        raise SystemExit(f"Rebuilt series must be MWh only, got {units} — investigate before continuing")

    if not stored:
        raise SystemExit("Rebuilt series is empty — the ClickHouse backfill has probably not landed")

    if stored > attempted:
        raise SystemExit(
            f"Rebuilt series holds {stored} rows but the rebuild only attempted {attempted}. The incremental "
            f"milestone worker wrote {stored - attempted} rows into the purge/rebuild window that the "
            f"full-history rebuild would not have produced. Re-run from a quiet moment."
        )

    if stored < attempted:
        raise SystemExit(
            f"Rebuilt series holds {stored} rows but the rebuild attempted {attempted} — rows were dropped on "
            f"insert. Investigate before continuing."
        )


async def _purge_demand_energy_milestones() -> None:
    """Delete the series under a transaction-scoped advisory lock so two runs cannot purge at once."""
    async with get_write_session() as session:
        await session.execute(text("select pg_advisory_xact_lock(:key)"), {"key": ADVISORY_LOCK_KEY})
        await session.execute(
            text("delete from milestones where record_id like :pattern"),
            {"pattern": DEMAND_ENERGY_RECORD_ID_PATTERN},
        )
        await session.commit()


def _log_existing(existing: list[tuple[str, int, str | None]], prefix: str) -> None:
    for record_id, count, unit in existing:
        logger.info(f"  {prefix} {count:>5} rows  {record_id}  [{unit}]")


async def repair_demand_energy_milestones(dry_run: bool = False) -> None:
    """Purge and regenerate the demand energy milestone series.

    Idempotent: the purge is keyed on record_id, and the rebuild re-derives the full history from
    ClickHouse, so re-running converges on the same series.
    """
    existing = await _summarise_existing()
    total = sum(count for _, count, _ in existing)
    units = sorted({unit for _, _, unit in existing if unit})

    logger.info(f"Found {total} demand energy milestone rows across {len(existing)} record ids, units: {units}")

    periods = await _periods_matched_by_purge()
    _assert_purge_matches_rebuild(periods)
    logger.info(f"Purge matches periods {periods}, all covered by the rebuild")

    if not NetworkNEM.data_first_seen:
        raise SystemExit("NetworkNEM.data_first_seen is not set — cannot bound the rebuild")

    start_date = NetworkNEM.data_first_seen.replace(tzinfo=None)
    end_date = get_last_completed_interval_for_network(NetworkNEM)

    if dry_run:
        _log_existing(existing, "would delete")
        rebuild_periods = ", ".join(period.value for period in REBUILD_PERIODS)
        logger.info(
            f"Dry run — would delete {total} rows then rebuild demand periods ({rebuild_periods}) over {start_date} to {end_date}"
        )
        return

    await _purge_demand_energy_milestones()
    logger.info(f"Deleted {total} demand energy milestone rows")

    records = await run_milestone_analysis(
        start_date=start_date,
        end_date=end_date,
        metrics=[MilestoneType.demand],
        periods=REBUILD_PERIODS,
    )
    attempted = {(record.record_id, record.interval) for record in records}
    logger.info(f"Rebuilt {len(attempted)} demand energy milestone records from {start_date} to {end_date}")

    rebuilt = await _summarise_existing()
    rebuilt_total = sum(count for _, count, _ in rebuilt)
    rebuilt_units = sorted({unit for _, _, unit in rebuilt if unit})
    _log_existing(rebuilt, "rebuilt")
    logger.info(f"Demand energy series now {rebuilt_total} rows, units: {rebuilt_units}")

    _assert_rebuild_sane(rebuilt_units, rebuilt_total, len(attempted))

    logger.info("Demand energy milestone repair complete")


def main() -> None:
    parser = argparse.ArgumentParser(description="Purge and rebuild the demand energy milestone series (#605)")
    parser.add_argument("--dry-run", action="store_true", help="Report what would change without writing")
    args = parser.parse_args()

    asyncio.run(repair_demand_energy_milestones(dry_run=args.dry_run))


if __name__ == "__main__":
    main()
